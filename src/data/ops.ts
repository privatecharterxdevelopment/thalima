function days(n: number, hour = 12) {
  const d = new Date()
  d.setDate(d.getDate() + n)
  d.setHours(hour, 0, 0, 0)
  return d.toISOString()
}

function hoursAgo(h: number) {
  return new Date(Date.now() - h * 3600_000).toISOString()
}

